using System.Text.Json;
using ReviewPlatform.Server.Contracts;

namespace ReviewPlatform.Server.AI;

// Accept historical text responses without pretending they were classified.
// New OCR responses have one authoritative, reading-ordered list of regions.
public static class DocumentVisionOutput
{
    public static DocumentVisionResult Parse(string content, bool allowPlainText = false, int depth = 0)
    {
        var candidate = StripFence(content.Trim());
        if (allowPlainText && ((!candidate.StartsWith('{') && !candidate.StartsWith('[') && !candidate.StartsWith('"')) ||
            candidate.StartsWith("[VISUAL_REGION_START]", StringComparison.Ordinal)))
            return Normalize(new(candidate));
        using var document = JsonDocument.Parse(candidate);
        var root = document.RootElement;
        if (root.ValueKind == JsonValueKind.String && depth < 2)
            return Parse(root.GetString()!, allowPlainText, depth + 1);
        if (root.ValueKind != JsonValueKind.Object)
            throw InvalidOutput();
        if (root.TryGetProperty("regions", out var regions) && regions.ValueKind != JsonValueKind.Null)
        {
            if (regions.ValueKind != JsonValueKind.Array || regions.GetArrayLength() > 200) throw InvalidOutput();
            var result = new List<DocumentVisionRegion>();
            foreach (var item in regions.EnumerateArray())
            {
                if (item.ValueKind != JsonValueKind.Object ||
                    !item.TryGetProperty("kind", out var kind) || kind.ValueKind != JsonValueKind.String ||
                    !item.TryGetProperty("text", out var text) || text.ValueKind != JsonValueKind.String)
                    throw InvalidOutput();
                var visual = false;
                if (item.TryGetProperty("visualRegion", out var boundary))
                {
                    if (boundary.ValueKind is not (JsonValueKind.True or JsonValueKind.False)) throw InvalidOutput();
                    visual = boundary.GetBoolean();
                }
                result.Add(new(kind.GetString()!, text.GetString()!, visual));
            }
            return Normalize(new("", result));
        }
        if (root.TryGetProperty("text", out var legacy) && legacy.ValueKind == JsonValueKind.String)
            return Normalize(new(legacy.GetString()!));
        throw InvalidOutput();
    }

    public static DocumentVisionResult Normalize(DocumentVisionResult result)
    {
        if (result.Text is null || result.Regions?.Count > 200) throw InvalidOutput();
        if (result.Regions is null)
        {
            if (result.Text.Length > 50_000) throw TooLong();
            return result with { Text = result.Text.Trim() };
        }
        if (result.Regions.Any(region => region is null || !DocumentContentKinds.IsValid(region.Kind) || region.Text is null))
            throw InvalidOutput();
        if (result.Regions.Sum(region => (long)region.Text.Length) > 50_000) throw TooLong();
        var regions = result.Regions.Select(region => region with { Text = region.Text.Trim() }).ToList();
        // Bound markers are generated by the application, never trusted in region text.
        if (regions.Any(region => region.Text.Contains("[VISUAL_REGION_", StringComparison.Ordinal) ||
            region.Text.Contains("[USER_INDEPENDENT_REGION_", StringComparison.Ordinal) ||
            region.Text.Contains("[CONTENT_KIND:", StringComparison.Ordinal) || region.Text.Contains("[/CONTENT_KIND]", StringComparison.Ordinal)))
            throw InvalidOutput();
        var text = string.Join("\n\n", regions.Where(region => !string.IsNullOrWhiteSpace(region.Text)).Select(region =>
            region.VisualRegion ? $"[VISUAL_REGION_START]\n{region.Text}\n[VISUAL_REGION_END]" : region.Text));
        if (text.Length > 50_000) throw TooLong();
        return new(text, regions);
    }

    private static string StripFence(string value)
    {
        if (!value.StartsWith("```", StringComparison.Ordinal)) return value;
        var first = value.IndexOf('\n');
        var last = value.LastIndexOf("```", StringComparison.Ordinal);
        return first >= 0 && last > first ? value[(first + 1)..last].Trim() : value;
    }

    private static LlmProviderRequestException InvalidOutput() => new("문서 이미지 분석의 영역 종류 또는 내용 형식이 올바르지 않습니다.");
    private static LlmProviderRequestException TooLong() => new("문서 이미지 분석의 응답이 너무 깁니다. (최대 50,000자)");
}
